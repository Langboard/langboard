"""Controlled external effects for the PostgreSQL graph process-restart test."""

import asyncio
import json
import os
import signal
from pathlib import Path
from typing import TypedDict
from langchain_core.messages import AIMessage, HumanMessage, ToolMessage
from langchain_core.tools import StructuredTool
from langgraph.checkpoint.postgres.aio import AsyncPostgresSaver
from langgraph.graph import END, START, StateGraph
from langgraph.types import Command, interrupt
from psycopg import AsyncConnection
from langboard_graph.core.graph.default.agent_loop import invoke_agent_loop


async def run():
    url = os.environ["LANGBOARD_FILE_TEST_DATABASE_URL"].replace("postgresql+psycopg://", "postgresql://")
    table = os.environ["LANGBOARD_RESTART_TABLE"]
    thread = os.environ["LANGBOARD_RESTART_THREAD"]

    async def echo(value: int):
        async with await AsyncConnection.connect(url, autocommit=True) as db:
            # Identifier is generated by the parent test, never by a model/user.
            await db.execute(f'INSERT INTO "{table}" (value) VALUES (%s)', (value,))
        return value

    async def approval(name, args):
        if args["value"] == 2:
            return None if interrupt({"name": name}) else "not approved"
        return None

    async def model(_, messages):
        if any(isinstance(m, ToolMessage) for m in messages):
            return AIMessage(content="done")
        return AIMessage(
            content="",
            tool_calls=[
                {"name": "echo", "id": f"call-{value}", "args": {"value": value}, "type": "tool_call"}
                for value in [1, 2]
            ],
        )

    tool = StructuredTool.from_function(coroutine=echo, name="echo", description="Controlled database effect")

    class State(TypedDict):
        response: str

    async def agent(state):
        result, _ = await invoke_agent_loop(None, None, [HumanMessage(content="run")], [tool], model, approval, 1)
        return {"response": result.content}

    graph = StateGraph(State)
    graph.add_node("agent", agent)
    graph.add_edge(START, "agent")
    graph.add_edge("agent", END)
    async with AsyncPostgresSaver.from_conn_string(url) as saver:
        compiled = graph.compile(checkpointer=saver)
        config = {"configurable": {"thread_id": thread}}
        if os.environ["LANGBOARD_RESTART_PHASE"] == "start":
            result = await compiled.ainvoke({}, config)
            assert result["__interrupt__"]
            Path(os.environ["LANGBOARD_RESTART_MARKER"]).write_text("checkpointed")
            # Parent kills the frozen worker after confirming persisted effects.
            os.kill(os.getpid(), signal.SIGSTOP)
        else:
            result = await compiled.ainvoke(Command(resume=True), config)
            assert result["response"] == "done"
            print(json.dumps({"response": result["response"]}))


if __name__ == "__main__":
    asyncio.run(run())
